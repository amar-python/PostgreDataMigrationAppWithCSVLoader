#!/usr/bin/env python3
"""Generate docs/TEST_CASES.md from the test tree (#169).

Usage:
    python3 scripts/test_catalogue.py          # write docs/TEST_CASES.md

Walks every test_*.py under tests/, extracts test functions/methods with their
docstrings and pytest markers, and produces a Markdown table grouped by file.

The output is not committed (it is gitignored). It changes with every test added
or moved, so a committed copy conflicted whenever two branches touched tests.
CI generates it on every run and attaches it as the `test-catalogue` artifact;
run this script to get a local copy.
"""
from __future__ import annotations

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TESTS_DIR = ROOT / "tests"
OUTPUT = ROOT / "docs" / "TEST_CASES.md"

MARKER_NAMES = {"unit", "integration", "e2e", "regression", "security",
                "snapshot", "parity", "system", "sit", "performance",
                "accessibility", "uat"}


def _extract_markers(decorators: list[ast.expr]) -> list[str]:
    """Return pytest marker names from decorator nodes."""
    markers: list[str] = []
    for dec in decorators:
        if isinstance(dec, ast.Attribute) and isinstance(dec.value, ast.Attribute):
            if (isinstance(dec.value.value, ast.Name)
                    and dec.value.value.id == "pytest"
                    and dec.value.attr == "mark"):
                markers.append(dec.attr)
        elif isinstance(dec, ast.Call) and isinstance(dec.func, ast.Attribute):
            attr = dec.func
            if isinstance(attr.value, ast.Attribute):
                if (isinstance(attr.value.value, ast.Name)
                        and attr.value.value.id == "pytest"
                        and attr.value.attr == "mark"):
                    markers.append(attr.attr)
    return markers


def _first_line_of_docstring(node: ast.AST) -> str:
    """Return the first non-empty line of the docstring, or ''."""
    ds = ast.get_docstring(node)
    if not ds:
        return ""
    for line in ds.splitlines():
        stripped = line.strip()
        if stripped:
            return stripped
    return ""


def _collect_tests(filepath: Path) -> list[dict]:
    """Parse one test file and return a list of test dicts."""
    try:
        tree = ast.parse(filepath.read_text(encoding="utf-8"), filename=str(filepath))
    except SyntaxError:
        return []

    tests: list[dict] = []
    rel = filepath.relative_to(ROOT)

    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef):
            class_markers = _extract_markers(node.decorator_list)
            for item in node.body:
                if isinstance(item, ast.FunctionDef) and item.name.startswith("test"):
                    markers = class_markers + _extract_markers(item.decorator_list)
                    tests.append({
                        "file": str(rel),
                        "class": node.name,
                        "name": item.name,
                        "line": item.lineno,
                        "markers": sorted(set(m for m in markers if m in MARKER_NAMES)),
                        "objective": _first_line_of_docstring(item),
                    })
        elif isinstance(item := node, ast.FunctionDef) and item.name.startswith("test"):
            markers = _extract_markers(item.decorator_list)
            tests.append({
                "file": str(rel),
                "class": "",
                "name": item.name,
                "line": item.lineno,
                "markers": sorted(set(m for m in markers if m in MARKER_NAMES)),
                "objective": _first_line_of_docstring(item),
            })

    return tests


def generate() -> str:
    """Generate the full TEST_CASES.md content."""
    all_tests: list[dict] = []
    for py in sorted(TESTS_DIR.rglob("test_*.py")):
        all_tests.extend(_collect_tests(py))

    lines: list[str] = []
    lines.append("# Test Catalogue")
    lines.append("")
    lines.append("> Auto-generated by `scripts/test_catalogue.py` — do not edit by hand.")
    lines.append(f"> {len(all_tests)} tests across {len(set(t['file'] for t in all_tests))} files.")
    lines.append("")
    lines.append("To regenerate: `python3 scripts/test_catalogue.py`")
    lines.append("")

    # Group by file
    current_file = ""
    for t in all_tests:
        if t["file"] != current_file:
            current_file = t["file"]
            lines.append(f"## `{current_file}`")
            lines.append("")
            lines.append("| Test | Markers | Objective |")
            lines.append("|---|---|---|")

        markers_str = ", ".join(t["markers"]) if t["markers"] else "—"
        name = f"`{t['class']}.{t['name']}`" if t["class"] else f"`{t['name']}`"
        obj = t["objective"] or "—"
        lines.append(f"| {name} | {markers_str} | {obj} |")
        lines.append("")

    lines.append("")
    return "\n".join(lines)


def main() -> int:
    fresh = generate()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(fresh, encoding="utf-8")
    count = fresh.count("| `")
    print(f"Wrote docs/TEST_CASES.md ({count} tests)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
