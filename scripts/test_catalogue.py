#!/usr/bin/env python3
"""Generate docs/TEST_CASES.md — every test, its ID, file and objective (#169).

    python scripts/test_catalogue.py            # rewrite docs/TEST_CASES.md
    python scripts/test_catalogue.py --check    # exit 1 if the committed doc is stale

Tests are collected by pytest itself (not parsed from source), so inherited
tests (tests/system_integration/environments/*), unittest classes and
parametrised cases are listed exactly as they run. Nothing is executed and no
database is needed.

ID: an explicit `@pytest.mark.id("UAT-04-1")` wins; otherwise the pytest node id
(`tests/unit/test_x.py::Class::test_y`), which is stable until the test moves.
Objective: the first line of the test's docstring, else the class's, else "—".
Backfilling IDs and docstrings is deliberately out of scope (#169).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "TEST_CASES.md"
FIX = "run `python scripts/test_catalogue.py` and commit the result"


def _first_line(doc: str | None) -> str:
    for line in (doc or "").strip().splitlines():
        if line.strip():
            return line.strip()
    return ""


def _collect() -> list[dict]:
    import pytest

    rows: list[dict] = []

    class _Grab:
        def pytest_collection_modifyitems(self, items):
            for it in items:
                mark = it.get_closest_marker("id")
                cls = getattr(it, "cls", None)
                objective = _first_line(getattr(it.obj, "__doc__", None)) or _first_line(
                    getattr(cls, "__doc__", None) if cls else None)
                rel = it.nodeid.split("::")[0]
                rows.append({
                    "id": str(mark.args[0]) if mark and mark.args else it.nodeid,
                    "explicit": bool(mark and mark.args),
                    "file": rel,
                    "category": rel.split("/")[1] if rel.count("/") > 1 else "(root)",
                    "objective": objective or "—",
                })

    code = pytest.main(["--collect-only", "-p", "no:terminal", "-p", "no:cacheprovider",
                        "-o", "addopts=", str(ROOT / "tests")], plugins=[_Grab()])
    if code != 0:
        sys.exit(f"pytest collection failed (exit {code}); fix that before cataloguing")
    return rows


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def render(rows: list[dict]) -> str:
    rows = sorted(rows, key=lambda r: (r["category"], r["file"], r["id"]))
    out = [
        "# Test cases",
        "",
        "<!-- GENERATED by scripts/test_catalogue.py — do not edit by hand. -->",
        "",
        f"{len(rows)} tests, collected by pytest. Regenerate with "
        "`python scripts/test_catalogue.py`; CI fails if this file is stale "
        "(`--check`).",
        "",
        "An ID is an explicit `@pytest.mark.id(\"…\")` if the test has one, otherwise "
        "its pytest node id. “—” means the test has no docstring yet.",
        "",
    ]
    cats: dict[str, list[dict]] = {}
    for r in rows:
        cats.setdefault(r["category"], []).append(r)
    out += ["| Category | Tests |", "|---|---|"]
    out += [f"| `{c}` | {len(v)} |" for c, v in cats.items()]
    for cat, items in cats.items():
        out += ["", f"## {cat} ({len(items)})", "", "| ID | File | Objective |", "|---|---|---|"]
        for r in items:
            out.append(f"| `{_cell(r['id'])}` | `{r['file']}` | {_cell(r['objective'])} |")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="fail if docs/TEST_CASES.md differs from a fresh generation")
    args = ap.parse_args()

    sys.path.insert(0, str(ROOT))
    fresh = render(_collect())
    if args.check:
        current = DOC.read_text(encoding="utf-8") if DOC.exists() else ""
        if current != fresh:
            print(f"docs/TEST_CASES.md is out of date — {FIX}.", file=sys.stderr)
            return 1
        print("docs/TEST_CASES.md is up to date.")
        return 0
    DOC.write_text(fresh, encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
