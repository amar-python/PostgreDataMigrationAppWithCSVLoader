#!/usr/bin/env python3
"""Generate docs/TEST_CASES.md — every test case grouped by test category.

Sources:
  * pytest tests under tests/<group>/ (collected statically with ast — no
    imports, no database). Objective = first line of the test's docstring,
    falling back to the humanised test name; parametrised tests list their
    case count.
  * vitest tests under csv-table-hub-main/src/__tests__/<group>/ (it/test titles).
  * the SQL assertion suite (counted per suite file).

Usage:
    python3 scripts/test_catalogue.py            # rewrite docs/TEST_CASES.md
    python3 scripts/test_catalogue.py --check    # exit 1 if the file is stale
"""
from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "TEST_CASES.md"

GROUPS = [
    ("unit", "Unit tests", "UT",
     "Single functions and modules in isolation. No database, no network."),
    ("system", "System tests", "ST",
     "The whole backend (API + services + PostgreSQL + shell pipeline) through its public interfaces."),
    ("system_integration", "System integration tests", "SIT",
     "Contracts between components: API and frontend, API and PostgreSQL, deploy scripts, environments."),
    ("performance", "Performance tests", "PT",
     "Throughput, latency and resource bounds. Budgets scale with PERF_BUDGET_SCALE."),
    ("accessibility", "Accessibility tests", "AT",
     "WCAG 2.1 A/AA on the React frontend with Playwright + axe-core, plus keyboard and reflow checks."),
    ("uat", "User acceptance tests", "UAT",
     "User stories written as Given/When/Then and run against the API."),
]

FRONTEND_TESTS = ROOT / "csv-table-hub-main" / "src" / "__tests__"
SQL_SUITES = ROOT / "tests" / "suites"


def _md(text: str) -> str:
    """Escape docstring text for a Markdown table cell."""
    for ch in ("\\", "|", "*", "_", "`"):
        text = text.replace(ch, "\\" + ch)
    return text.replace("<", "&lt;").replace(">", "&gt;")


def _humanise(name: str) -> str:
    return name.removeprefix("test_").replace("_", " ").strip().capitalize()


def _objective(node: ast.AST) -> str:
    doc = ast.get_docstring(node) or ""
    first = " ".join(doc.strip().split("\n\n")[0].split())
    # Drop a leading case ID such as "SYS-03" — the catalogue assigns its own.
    first = re.sub(r"^[A-Z0-9]+-\d+\s+", "", first)
    return _md(first or _humanise(getattr(node, "name", "")))


def _param_count(fn: ast.FunctionDef) -> int:
    total = 1
    for dec in fn.decorator_list:
        if (isinstance(dec, ast.Call) and getattr(dec.func, "attr", "") == "parametrize"
                and len(dec.args) >= 2):
            values = dec.args[1]
            if isinstance(values, (ast.List, ast.Tuple)):
                total *= max(len(values.elts), 1)
            elif isinstance(values, ast.Call):  # list(...) etc. — count unknown
                total *= 1
    return total


def _python_cases(path: Path):
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            for item in node.body:
                if isinstance(item, ast.FunctionDef) and item.name.startswith("test"):
                    yield f"{node.name}.{item.name}", _objective(item), _param_count(item)
        elif isinstance(node, ast.FunctionDef) and node.name.startswith("test"):
            yield node.name, _objective(node), _param_count(node)


_IT_RE = re.compile(r"""\b(?:it|test)(?:\.each\([^)]*\))?\(\s*(["'`])(.+?)\1""")


def _vitest_cases(path: Path):
    for m in _IT_RE.finditer(path.read_text(encoding="utf-8")):
        yield _md(m.group(2))


def build() -> str:
    lines = [
        "# Test cases",
        "",
        "Every automated test case in the repository, grouped by test category.",
        "Generated by `scripts/test_catalogue.py`; do not edit by hand. Run",
        "`make test-catalogue` after adding or changing tests. How to run each group",
        "is in [`tests/README.md`](../tests/README.md).",
        "",
        "Each row is one test function. **Cases** is the number of executions",
        "after parametrisation. The objective is the test's docstring, which states",
        "the behaviour asserted, and therefore the expected result.",
        "",
    ]
    summary, sections = [], []
    for folder, title, prefix, blurb in GROUPS:
        rows, n, cases = [], 0, 0
        for path in sorted((ROOT / "tests" / folder).rglob("test_*.py")):
            rel = path.relative_to(ROOT).as_posix()
            for name, objective, count in _python_cases(path):
                n += 1
                cases += count
                rows.append(f"| {prefix}-{n:03d} | `{rel}` | `{name}` | {objective} | {count} |")
        frontend_dir = FRONTEND_TESTS / folder
        for path in sorted(frontend_dir.rglob("*.test.ts*")) if frontend_dir.exists() else []:
            rel = path.relative_to(ROOT).as_posix()
            for title_ in _vitest_cases(path):
                n += 1
                cases += 1
                rows.append(f"| {prefix}-{n:03d} | `{rel}` | vitest | {title_} | 1 |")
        if folder == "system_integration" and SQL_SUITES.exists():
            for path in sorted(SQL_SUITES.glob("test_*.sql")):
                count = len(re.findall(r"\bassert_\w+\s*\(", path.read_text(encoding="utf-8")))
                n += 1
                cases += count
                rel = path.relative_to(ROOT).as_posix()
                rows.append(f"| {prefix}-{n:03d} | `{rel}` | SQL suite | "
                            f"T&E schema constraints and business rules ({count} assertions) | {count} |")
        summary.append(f"| [{title}](#{title.lower().replace(' ', '-')}) | `tests/{folder}/` | {n} | {cases} |")
        sections += [f"## {title}", "", blurb, "",
                     "| ID | File | Test | Objective / expected result | Cases |",
                     "|----|------|------|-----------------------------|-------|", *rows, ""]
    lines += ["## Summary", "", "| Category | Folder | Tests | Cases |",
              "|----------|--------|-------|-------|", *summary, ""]
    return "\n".join(lines + sections).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if docs/TEST_CASES.md is stale")
    args = ap.parse_args()
    content = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != content:
            print("docs/TEST_CASES.md is stale — run: python3 scripts/test_catalogue.py")
            return 1
        print("docs/TEST_CASES.md is up to date")
        return 0
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
